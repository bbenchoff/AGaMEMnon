#!/usr/bin/env python3
"""Build and optionally hardware-test protocol-valid HWDATA nibble captures.

Each of eight small designs delays the AHB address-phase write qualifier by
one fabric clock, captures four HWDATA lanes together in the data phase, and
returns those bits on their corresponding HRDATA lanes.  Across the campaign
every physical bit of the 32-bit write-data bus is exercised without asking a
single qualification image to solve an unrelated 32-lane exit-placement
problem.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


def verilog(group: int) -> str:
    base = 4 * group
    lines = [
        "// generated by qualification/mcu_ahb32_write_campaign.py; group=%d" % group,
        "module top(input clk);",
        "  wire [3:0] hwdata;",
        "  wire hwrite, htrans1;",
        "  reg write_data_phase = 1'b0;",
        "  reg [3:0] captured = 4'b0;",
        "  (* keep *) MCU_DIN mcu_hwrite(.DIN(hwrite));",
        "  (* keep *) MCU_DIN mcu_htrans1(.DIN(htrans1));",
    ]
    for index in range(4):
        lines.append("  (* keep *) MCU_DIN mcu_hwdata%d(.DIN(hwdata[%d]));" %
                     (base + index, index))
    lines += [
        "  always @(posedge clk) begin",
        "    write_data_phase <= hwrite & htrans1;",
        "    if (write_data_phase) captured <= hwdata;",
        "  end",
    ]
    for index in range(4):
        lines.append("  (* keep *) MCU_DOUT mcu_h%d(.DOUT(captured[%d]));" %
                     (base + index, index))
    lines += ["endmodule", ""]
    return "\n".join(lines)


def sha256_binary(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def sha256_text(path: Path) -> str:
    data = path.read_bytes().replace(b"\r\n", b"\n").replace(b"\r", b"\n")
    return hashlib.sha256(data).hexdigest()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--groups", default="0,1,2,3,4,5,6,7")
    parser.add_argument("--out-dir", type=Path, default=Path(".tmp/mcu_ahb32_write"))
    parser.add_argument("--hardware-runner", type=Path)
    parser.add_argument("--evidence", type=Path,
                        default=Path("qualification/mcu_ahb32_write_evidence.jsonl"))
    args = parser.parse_args(argv)
    groups = [int(item) for item in args.groups.split(",") if item.strip()]
    if not groups or any(group < 0 or group > 7 for group in groups):
        raise SystemExit("groups must be comma-separated values in 0..7")
    args.out_dir.mkdir(parents=True, exist_ok=True)

    args.evidence.parent.mkdir(parents=True, exist_ok=True)
    completed = 0
    for group in groups:
        source = args.out_dir / ("write_group%d.v" % group)
        image = args.out_dir / ("write_group%d.bin" % group)
        source.write_text(verilog(group), encoding="ascii", newline="\n")
        build_cmd = [sys.executable, "-m", "agamemnon.cli", "build", str(source),
                     "--uarch", "--verify", "-o", str(image)]
        built = subprocess.run(build_cmd, text=True, capture_output=True)
        print(built.stdout, end="")
        if built.returncode:
            print(built.stderr, end="", file=sys.stderr)
            raise SystemExit("group %d build failed" % group)
        record = {
            "time_utc": datetime.now(timezone.utc).isoformat(),
            "group": group,
            "lanes": list(range(4 * group, 4 * group + 4)),
            "source_sha256": sha256_text(source),
            "bitstream_sha256": sha256_binary(image),
            "build": "pass",
            "hardware": "not-run",
        }
        if args.hardware_runner:
            run_cmd = [sys.executable, str(args.hardware_runner), str(image), str(group)]
            tested = subprocess.run(run_cmd, text=True, capture_output=True)
            print(tested.stdout, end="")
            if tested.returncode:
                print(tested.stderr, end="", file=sys.stderr)
                raise SystemExit("group %d hardware test failed" % group)
            record["hardware"] = "pass"
            record["hardware_output"] = tested.stdout.strip()
        # Append after each hardware-qualified image so a later routing failure
        # cannot discard already completed lane evidence.
        with args.evidence.open("a", encoding="utf-8", newline="\n") as stream:
            stream.write(json.dumps(record, sort_keys=True) + "\n")
        completed += 1

    print("qualified %d group(s); evidence appended to %s" % (completed, args.evidence))


if __name__ == "__main__":
    main()
